/**
 * Generates the SQL migration that seeds every template for every book format.
 *
 * Source of truth: src/lib/editor/formats.json + src/lib/editor/templateBuilder.mjs
 * Output:          src/supabase/migrations/00011_templates_expansion.sql
 *
 * Usage: node scripts/seed-templates.mjs
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  TEMPLATE_LAYOUTS,
  TEMPLATE_SPREAD_LAYOUTS,
  SPREAD_GAP_PX,
  buildSpreadTemplateSlots,
  buildTemplateSlots,
} from "../src/lib/editor/templateBuilder.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const PAGE_DPI = 300;
const DNS_NAMESPACE = "6ba7b810-9dad-11d1-80b4-00c04fd430c8";

const formats = JSON.parse(
  readFileSync(resolve(root, "src/lib/editor/formats.json"), "utf8")
);

function uuidV5(name, namespace = DNS_NAMESPACE) {
  const nsBytes = Buffer.from(namespace.replace(/-/g, ""), "hex");
  const hash = createHash("sha1")
    .update(nsBytes)
    .update(Buffer.from(name, "utf8"))
    .digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.subarray(0, 16).toString("hex");
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20, 32),
  ].join("-");
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = [];
const ids = [];
for (const raw of formats) {
  const definition = {
    key: raw.key,
    w: Math.round(raw.widthIn * PAGE_DPI),
    h: Math.round(raw.heightIn * PAGE_DPI),
  };

  for (const layout of TEMPLATE_LAYOUTS) {
    const slots = buildTemplateSlots(layout, definition.w, definition.h);
    const id = uuidV5(`picfoto:${definition.key}:${layout.id}`);
    ids.push(id);
    rows.push(
      `  (${sqlString(id)}, ${sqlString(layout.name)}, ${sqlString(
        layout.description
      )}, ${sqlString(definition.key)}, 'page', ${sqlString(
        layout.kind ?? "gallery"
      )}, ${sqlString(JSON.stringify(slots))}::jsonb, true, 'seed')`
    );
  }

  for (const layout of TEMPLATE_SPREAD_LAYOUTS) {
    const slots = buildSpreadTemplateSlots(layout, definition.w, definition.h, {
      gapPx: SPREAD_GAP_PX,
    });
    const id = uuidV5(`picfoto:${definition.key}:spread:${layout.id}`);
    ids.push(id);
    rows.push(
      `  (${sqlString(id)}, ${sqlString(layout.name)}, ${sqlString(
        layout.description
      )}, ${sqlString(definition.key)}, 'spread', 'spread', ${sqlString(
        JSON.stringify(slots)
      )}::jsonb, true, 'seed')`
    );
  }
}

const formatList = formats.map((f) => sqlString(f.key)).join(", ");
const idList = ids.map((id) => sqlString(id)).join(", ");

const sql = `-- AUTO-GENERATED by scripts/seed-templates.mjs — do not edit by hand.
-- Physical bleed (sangrado a corte) + stable-id catalog + seed ownership.
-- Conflict target is the deterministic id (NOT name), so renaming a template
-- updates the same row and never orphans project_pages.template_id references.

-- ── Template metadata: scope (page | spread), kind and source ───────
ALTER TABLE templates
  ADD COLUMN IF NOT EXISTS scope TEXT NOT NULL DEFAULT 'page';

ALTER TABLE templates
  ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'gallery';

-- Marks who owns a row: 'seed' (system catalog) or 'custom' (created outside).
ALTER TABLE templates
  ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'custom';

-- ── Templates are system-seeded and regenerated ─────────────
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'templates_name_format_key'
  ) THEN
    ALTER TABLE templates
      ADD CONSTRAINT templates_name_format_key UNIQUE (name, format);
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'templates_scope_check'
  ) THEN
    ALTER TABLE templates
      ADD CONSTRAINT templates_scope_check CHECK (scope IN ('page', 'spread'));
  END IF;
END $$;

-- ── Templates: upsert by stable id (rename-safe, reference-preserving) ──
-- NOTE: the photo_placements → media coordinate shift lives ONLY in
-- 00012_templates_physical_bleed.sql so it is never applied twice.
INSERT INTO templates (id, name, description, format, scope, kind, slots, is_active, source) VALUES
${rows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  description = EXCLUDED.description,
  scope = EXCLUDED.scope,
  kind = EXCLUDED.kind,
  slots = EXCLUDED.slots,
  is_active = EXCLUDED.is_active,
  source = EXCLUDED.source;

-- Only deactivate rows OWNED by the seed and in these formats; custom templates
-- are left untouched.
UPDATE templates
SET is_active = false
WHERE source = 'seed'
  AND format IN (${formatList})
  AND id NOT IN (${idList});
`;

const outputPath = resolve(
  root,
  "src/supabase/migrations/00016_templates_source.sql"
);
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, sql, "utf8");
console.log(
  `Wrote ${rows.length} templates (${TEMPLATE_LAYOUTS.length} page + ${TEMPLATE_SPREAD_LAYOUTS.length} spread layouts × ${formats.length} formats) → ${outputPath}`
);
